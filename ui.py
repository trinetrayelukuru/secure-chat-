def _art_lines(art: str) -> tuple:
    """Split an artwork block into rows, dropping trailing padding."""
    return tuple(line.rstrip() for line in art.splitlines() if line.strip())


_BANNER_LINES = _art_lines(_BANNER_ART)
_BANNER_WIDTH = max(len(line) for line in _BANNER_LINES)

# Word-wrapped form: the same two words stacked, so the logo still fits.
_BANNER_STACK = (_art_lines(_BANNER_SECURE_ART), _art_lines(_BANNER_CHAT_ART))
_BANNER_STACK_WIDTH = max(max(len(line) for line in group) for group in _BANNER_STACK)

_USER_COLOURS = (CYAN, GREEN, YELLOW, MAGENTA, WHITE)


def _enable_windows_ansi() -> bool:
    """Turn on virtual-terminal escapes for the current Windows console."""
    try:
        kernel32 = ctypes.windll.kernel32
        handle = kernel32.GetStdHandle(-11)  # STD_OUTPUT_HANDLE
        mode = ctypes.c_uint32()
        if not kernel32.GetConsoleMode(handle, ctypes.byref(mode)):
            return False
        vt_flag = 0x0004  # ENABLE_VIRTUAL_TERMINAL_PROCESSING
        if mode.value & vt_flag:
            return True
        return bool(kernel32.SetConsoleMode(handle, mode.value | vt_flag))
    except Exception:
        return False


def _detect_colour() -> bool:
    choice = os.environ.get("SECURECHAT_COLOR", "").strip().lower()
    if choice == "always":
        return True
    if choice == "never" or os.environ.get("NO_COLOR"):
        return False
    if not getattr(sys.stdout, "isatty", lambda: False)():
        return False
    if os.name == "nt":
        return _enable_windows_ansi()
    return os.environ.get("TERM", "").strip().lower() != "dumb"


COLOR = _detect_colour()

# One lock for every UI write.  The server announces joins/leaves from several
# handler threads and the client prints incoming messages from its receive
# thread, so a line must never be written in two pieces.
_PRINT_LOCK = threading.RLock()


def write(text: str) -> None:
    """Write text as given, atomically with respect to all other UI output."""
    with _PRINT_LOCK:
        sys.stdout.write(text)
        sys.stdout.flush()


def _write(line: str = "") -> None:
    """Write one complete, already formatted line."""
    write(line + "\n")


def paint(text: str, *codes: str) -> str:
    """Wrap text in ANSI codes, or return it untouched when colour is off."""
    if not COLOR or not codes:
        return text
    return "".join(codes) + text + RESET


def clock() -> str:
    """Local wall-clock time used by every timestamped line."""
    return datetime.now().strftime("%H:%M:%S")


# --- Banner -----------------------------------------------------------------
def _columns() -> int:
    """Current terminal width, with a safe default when output is redirected."""
    try:
        return shutil.get_terminal_size((80, 24)).columns
    except OSError:
        return 80


def _compact_banner(role: str, port: int, columns: int) -> None:
    """Short header used when the window is too narrow for the artwork."""
    label = "SERVER CONSOLE" if role == "server" else "CLIENT CONSOLE"
    # Never emit a line wider than the terminal - wrapping is what destroys
    # the header once the artwork no longer fits.
    limit = max(1, columns - 1)
    rule = "=" * min(limit, 58)
    lines = [
        paint(rule, CYAN, BOLD),
        paint("SECURE CHAT"[:limit], CYAN, BOLD),
        paint(f"Encrypted Multi-Client Chat | TCP Port {port}"[:limit], MAGENTA),
        paint(f"v{VERSION} | {label}"[:limit], CYAN, BOLD),
        paint(rule, CYAN, BOLD),
        "",
    ]
    with _PRINT_LOCK:
        for line in lines:
            _write(line)


def _banner_footer(role: str, port: int) -> None:
    """Subtitle and version/role lines printed under the shared heading."""
    _write(
        "  "
        + paint("SECURE CHAT", CYAN, BOLD)
        + paint("  |  ", GREY)
        + paint("Encrypted Multi-Client Chat", MAGENTA)
        + paint("  |  ", GREY)
        + paint(f"TCP Port {port}", YELLOW, BOLD)
    )
    label = "SERVER CONSOLE" if role == "server" else "CLIENT CONSOLE"
    _write(
        "  "
        + paint(f"v{VERSION}", GREY)
        + paint("  |  ", GREY)
        + paint(label, CYAN, BOLD)
    )
    _write()


def banner(role: str = "client", port: int = DEFAULT_PORT) -> None:
    """Print the one shared SecureChat banner for the server and the client.

    Both programs use the same Isometric1 artwork in the same colour; only the
    role label underneath changes.  Wide terminals get the logo on one line,
    ordinary terminals get the same words stacked (which is how the font wraps
    at this width), and only a very narrow window falls back to the compact
    header.  Lines are never allowed to wrap on their own.
    """
    columns = _columns()

    # Keep one spare column so the longest line can never trigger a wrap.
    if _BANNER_WIDTH < columns:
        groups = (_BANNER_LINES,)
    elif _BANNER_STACK_WIDTH < columns:
        groups = _BANNER_STACK
    else:
        _compact_banner(role, port, columns)
        return

    with _PRINT_LOCK:
        for group in groups:
            width = max(len(line) for line in group)
            pad = " " * max(0, (columns - width) // 2)
            for line in group:
                _write(pad + paint(line, CYAN, BOLD))
        _write()
        _banner_footer(role, port)


# --- Panels and events ------------------------------------------------------
def panel(title: str, rows, width: int = 58) -> None:
    """Print an aligned key/value panel with an ASCII border."""
    edge = paint("+" + "-" * (width - 2) + "+", GREY)
    lines = [
        edge,
        paint("| ", GREY)
        + paint(title[: width - 4].ljust(width - 4), CYAN, BOLD)
        + paint(" |", GREY),
        paint("|" + "-" * (width - 2) + "|", GREY),
    ]
    for label, value in rows:
        label_text = f"{label:<12}"
        gap = max(0, width - 3 - len(label_text) - len(value))
        lines.append(
            paint("| ", GREY)
            + paint(label_text, GREY)
            + paint(value, WHITE)
            + " " * gap
            + paint("|", GREY)
        )
    lines.append(edge)
    with _PRINT_LOCK:
        for line in lines:
            _write(line)


_KINDS = {
    "join": ("JOIN", GREEN),
    "leave": ("LEAVE", YELLOW),
    "ready": ("READY", GREEN),
    "warn": ("WARN", YELLOW),
    "error": ("ERROR", RED),
    "info": ("INFO", CYAN),
}


def event(kind: str, message: str, suffix: str = "") -> None:
    """Timestamped server/console event, e.g. JOIN / LEAVE / ERROR."""
    tag, colour = _KINDS.get(kind, ("INFO", CYAN))
    line = (
        "  "
        + paint(f"[{clock()}]", GREY)
        + " "
        + paint(f"{tag:<5}", colour, BOLD)
        + " "
        + message
    )
    if suffix:
        line += paint(f"  |  {suffix}", GREY)
    with _PRINT_LOCK:
        _write(line)


# --- Client message lines ---------------------------------------------------
def _user_colour(username: str) -> str:
    return _USER_COLOURS[sum(ord(char) for char in username) % len(_USER_COLOURS)]


def chat_line(username: str, text: str) -> str:
    stamp = paint(f"[{clock()}]", GREY)
    body = paint(f"[{username}]: {text}", _user_colour(username))
    return f"{stamp} {body}"


def system_line(text: str) -> str:
    return paint(f"[{clock()}]", GREY) + " " + paint(f"[System] {text}", MAGENTA)


def error_line(text: str) -> str:
    return paint(f"[{clock()}]", GREY) + " " + paint(f"[Error] {text}", RED)


def users_line(users) -> str:
    listing = ", ".join(users) if users else "nobody"
    return paint(
        f"=== Online users ({len(users)}): {listing} ===", CYAN, BOLD
    )


def prompt() -> str:
    return paint("  >> ", GREEN, BOLD)


def input_prompt(label: str) -> str:
    return paint(f"  {label} >> ", CYAN, BOLD)


def help_panel() -> None:
    panel(
        "COMMANDS",
        [("/users", "list everyone online"), ("/quit", "leave the chat")],
    )


def server_panel(host: str, port: int) -> None:
    panel(
        "SERVER",
        [
            ("STATUS", "RUNNING"),
            ("LISTEN", f"{host}:{port}"),
            ("ENCRYPTION", "Fernet (shared key)"),
            ("USERS", "0 connected"),
        ],
    )


def client_panel(host: str, port: int) -> None:
    panel(
        "CONNECTION",
        [
            ("SERVER", f"{host}:{port}"),
            ("STATUS", "connecting ..."),
            ("ENCRYPTION", "Fernet (shared key)"),
        ],
    )


def connection_failed(host: str, port: int, reason: str) -> None:
    panel(
        "CONNECTION FAILED",
        [
            ("SERVER", f"{host}:{port}"),
            ("REASON", reason),
            ("NEXT", "start server.py, then run client.py again"),
        ],
    )
