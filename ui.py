"""Terminal presentation helpers for SecureChat (UI only).

Nothing in this module touches sockets, encryption, sessions or the wire
protocol - it only formats text.  ANSI colour is enabled for a real terminal
that supports it and falls back to plain text otherwise.  Set
SECURECHAT_COLOR=always or SECURECHAT_COLOR=never to override the detection.
"""

